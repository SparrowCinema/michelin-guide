"""Generate browser search aliases from build.py without executing the data builder."""
import ast, json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
CURATED = {
    '哥本哈根':['Copenhagen','Kobenhavn','København'], '罗马':['Rome','Roma'],
    '雅典':['Athens','Athina'], '纽约':['New York','NYC'],
    '胡志明市':['Ho Chi Minh City','Saigon','西贡'], '槟城乔治市':['George Town','Penang','槟城'],
    '中国内地':['China','Mainland China','中国大陆'], '英国':['UK','Britain'],
    '美国':['United States','USA','US'], '土耳其':['Turkey','Türkiye'],
    '首尔':['Seoul','汉城'], '台北':['Taipei','臺北'],
}
aliases = {}
for node in ast.parse((ROOT/'tools/build.py').read_text()).body:
    data = None
    if isinstance(node, ast.Assign) and any(isinstance(t,ast.Name) and t.id in ['CITY','CUISINE'] for t in node.targets):
        data = ast.literal_eval(node.value)
    if isinstance(node, ast.Expr) and isinstance(node.value,ast.Call):
        f=node.value.func
        if isinstance(f,ast.Attribute) and isinstance(f.value,ast.Name) and f.value.id=='CUISINE' and f.attr=='update':
            data=ast.literal_eval(node.value.args[0])
    if data:
        for en,zh in data.items(): aliases.setdefault(zh,[]).append(en)
for zh,names in CURATED.items():aliases[zh]=list(dict.fromkeys(aliases.get(zh,[])+names))
(ROOT/'search-aliases.js').write_text('/* Generated by tools/build_search_aliases.py. */\nwindow.MG_ALIASES = '+json.dumps(aliases,ensure_ascii=False,separators=(',',':'))+';\n')
